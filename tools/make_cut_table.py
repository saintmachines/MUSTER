#!/usr/bin/env python3
"""Write gate/cut_table.json: for every row of the 24 final legs, the unit count and the hashes of the unit list and
of the parent labels under the leg's preset. No benchmark text is written.

  EXPERIMENT_DIR=<tree with the benchmark files> python tools/make_cut_table.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import pandas as pd

from muster import presets
from muster.compat.verify import row_signature

M = os.environ["EXPERIMENT_DIR"]
out = {"about": "per row: units, unit_sig (the harness's reranker-cache corpus signature of the unit list), "
                "parent_sig (sha1 of the type-tagged parent labels), parents; generated by tools/make_cut_table.py",
       "legs": {}}
memo = {}
for tag, leg in sorted(presets.legs().items()):
    plan = presets.get(tag)
    df = pd.read_parquet(os.path.join(M, leg["parq"]))
    rows = {}
    for r in leg["rows"]:
        k = (leg["parq"], r, plan.branch, plan.atom, plan.chunk, plan.mscale)
        if k not in memo:
            memo[k] = row_signature(str(df["context"].iloc[r]), plan)
        rows[str(r)] = memo[k]
    out["legs"][tag] = rows
    print(tag, len(rows), flush=True)
json.dump(out, open(os.path.join(ROOT, "gate", "cut_table.json"), "w"), indent=1, sort_keys=True)
print("wrote gate/cut_table.json")
