#!/usr/bin/env python3
"""Generate muster/presets/paper.json from the released leg tables. Presets are generated, never typed.

  python tools/gen_presets.py            (from the repository root)

Reads harness/len_legs.json (the 18 final retrieval legs) and gate/legs_extra.json (FactConsolidation and LoCoMo),
groups the 24 legs into the nine presets, checks that every leg of a preset has the same environment apart from its
rows, and writes each preset with the source of every field.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GROUPS = {
    "mab.A": ["lz_shqa", "lz_mhqa", "lz_rec", "lz_b77", "lz_clin", "lz_nlu", "lz_trcC", "lz_trcF"],
    "mab.A1": ["lz_lme"],
    "mab.B": ["lz_evq", "lz_det", "lz_summ"],
    "mab.C": ["mg_fcsh_struct", "mg_fcmh_struct"],
    "beam.u20": ["lz_u20_beam100k", "lz_u20_beam1m", "lz_u20_beam10m"],
    "beam.u40": ["lz_u40_beam100k", "lz_u40_beam1m", "lz_u40_beam10m"],
    "locomo.u10": ["lcm_u10", "lcmrefc_u10"],
    "locomo.u20": ["lcm_u20"],
    "locomo.u5": ["lcm_u5"],
}
# keys that never reach a context (run mode and reader), so they may differ between legs of one preset
INERT = {"DRY", "DRY_XC", "DUMP_CTX", "ROUTER_ONLY", "RESUME", "OAMODEL", "TEMP", "NQ", "ROWS"}


def legs():
    out = {}
    for path in ("harness/len_legs.json", "gate/legs_extra.json"):
        for leg in json.load(open(os.path.join(ROOT, path)))["legs"]:
            out[leg["tag"]] = dict(leg, _file=path)
    return out


def policy(env, arm):
    a = arm.split("|")[0]
    if a.startswith("attprio_sess"):
        return "attprio_sess"
    if a.startswith("flrs"):
        return "flrs"
    if a.startswith("flr"):
        return "flr"
    raise SystemExit("unknown arm %r" % arm)


def preset(name, members, L):
    envs = [{k: v for k, v in L[t]["env"].items() if k not in INERT} for t in members]
    for t, e in zip(members, envs):
        if e != envs[0]:
            diff = sorted(k for k in set(e) | set(envs[0]) if e.get(k) != envs[0].get(k))
            raise SystemExit("preset %s: leg %s differs from %s on %s" % (name, t, members[0], diff))
    e, first = envs[0], L[members[0]]
    pol = policy(e, first["arm"])
    auto = e.get("AUTOSTRUCT") == "1"
    rounds = first["ds"] == "longmemeval"
    rend = e.get("RENDER", "flat")
    if auto:
        branch, atom, chunk, mscale, render = "numbered", None, None, 0, "numbered"
    elif rounds:
        branch, atom, chunk, mscale, render = "rounds", None, None, 0, "flat"
    else:
        atom = e["ATOM"]
        branch = "record" if atom == "blank" else "prose"
        chunk, mscale = int(e["CHUNK"]), int(e.get("MSCALE", "0") or 0)
        render = "r4" if rend in ("bgroup", "seg3") else "flat"
    chain = {"flat": "flat, read as built", "bgroup": "bgroup cap %s -> recover -> R4" % e.get("RGROUP_MAX"),
             "seg3": "seg3 cap %s, HBOND %s, HMARK %s -> recover -> R4" % (e.get("RGROUP_MAX"), e.get("HBOND", "doc"),
                                                                        e.get("HMARK", "off"))}[rend] if not auto else \
        "tagged -> strip \"[CURRENT] \""
    knobs = "CEML=%s|CEBS=%s|CE_SUBMAX=%s|CE_SUB_TOK=|CE_SLIDE=|name=BAAI/bge-reranker-v2-m3" % (
        e.get("CEML", "1024"), e.get("CEBS", "64"), e.get("CE_SUBMAX", ""))
    return {
        "branch": branch, "atom": atom, "chunk": chunk, "mscale": mscale, "U": int(e["U"]), "policy": pol,
        "render": render, "mode": "exact", "frozen": True, "supersede": "numbered" if auto else "off",
        "reference_chunk": 4096,
        "encoder": {"name": "BAAI/bge-m3", "revision": "5617a9f61b028005a4858fdac845db406aefb181", "max_length": int(e.get("EMB_MAXLEN", "448")),
                    "batch_size": 32, "dtype": "float32"},
        "reranker": {"name": "BAAI/bge-reranker-v2-m3", "revision": "953dc6f6f85a1b2dbfca4c34a2796e7dde08d41e",
                     "max_length": int(e.get("CEML", "1024")), "batch_size": int(e.get("CEBS", "64")), "dtype": "float32"},
        "compat": {"legs": members, "env": e, "arm": first["arm"], "chain": chain, "knobs": knobs,
                   "cache": e.get("CE_CACHE") == "1", "floors_lt10": e.get("FLOORS_LT10", ""),
                   "sources": sorted({L[t]["_file"] for t in members})},
        "stats": None, "source": "preset:" + name,
        "trace": ["generated by tools/gen_presets.py from %s" % ", ".join(sorted({L[t]["_file"] for t in members}))],
    }


def main():
    L = legs()
    missing = [t for g in GROUPS.values() for t in g if t not in L]
    if missing:
        sys.exit("legs missing from the tables: %s" % missing)
    out = {name: preset(name, members, L) for name, members in GROUPS.items()}
    leg_index = {t: {"preset": name, "parq": L[t]["parq"], "rows": [int(x) for x in L[t]["rows"].strip(",").split(",")],
                     "nq": int(L[t]["nq"]), "ds": L[t]["ds"], "arm": L[t]["arm"]}
                 for name, members in GROUPS.items() for t in members}
    dest = os.path.join(ROOT, "muster", "presets", "paper.json")
    json.dump({"presets": out, "legs": leg_index}, open(dest, "w"), indent=1, sort_keys=True)
    print("wrote %s: %d presets, %d legs" % (os.path.relpath(dest, ROOT), len(out), len(leg_index)))


if __name__ == "__main__":
    main()
